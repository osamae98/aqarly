// The table encodes circles and rects inline rather than as path data, so a
// stop is either a primitive or a plain `d`.
function shape(d, i) {
  if (d.startsWith("circle:")) {
    const [cx, cy, r] = d.slice(7).split(",");
    return <circle key={i} cx={cx} cy={cy} r={r} />;
  }
  if (d.startsWith("rect:")) {
    const [x, y, w, h, rx] = d.slice(5).split(",");
    return <rect key={i} x={x} y={y} width={w} height={h} rx={rx} />;
  }
  return <path key={i} d={d} />;
}

export default function Icon({
  name,
  size = 20,
  strokeWidth = 2,
  className = "",
  ...props
}) {
  const paths = IconPaths[name];
  if (!paths) return null;

  return (
    <svg
      // `size` is free-form, so the box stays an inline style — the colour
      // still comes from `currentColor` and whatever token set it.
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      className={`block shrink-0 ${className}`}
      {...props}
    >
      {paths.map(shape)}
    </svg>
  );
}
